'''
EXERCÍCIO 8D — Montando Nome
Nome = "janier"
1. Percorra o nome usando for.
2. Crie uma variável chamada nome_formado.
3. Vá adicionando uma letra por vez.
4. No final, mostre o nome.
Resultado esperado:
janier
Pratique:
- for
- strings
- +=
'''
nome = 'janier'
nome_formado = ''

for letra in nome:
    nome_formado += letra

print(letra)