# EXERCÍCIO INPUT NÚMERICO - INT

n1 = input('Digite o primeiro número: ')
n2 = input('Digite o segundo número: ')

n1_int = int(n1)
n2_int = int(n2)


print(f'Soma: {n1_int + n2_int}')
print(f'Subtração: {n1_int - n2_int}')
print(f'Multiplicação: {n1_int * n2_int}')
print(f'Divisão: {n1_int / n2_int:.3f}')