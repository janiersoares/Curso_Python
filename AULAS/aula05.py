# Tipo de dado bool (boolean)
# Aao questionar algo em um programa,
# só existem duas respostas possiveis.
# SIM (TRUE) OU NÃO (FALSE)
# Existem vários operadores para questionar.
# Um deles é o (==) que é um operador lógico
# Que questiona se um valor é igual ao outro.
print(10 == 10) #Sim  (True) => (Verdadeiro)
print(10 == 12) #Não (False) => (Falso)

print(type(10 == 10)) 
print(type(10 == 15))