""" Python - linguagem de Programação
 Tipo de tipagem - Dinamica / Forte
 STR -> STRING -> Texto
 Strings são textos dentro de aspas
"""
# Aspas simples ''
print('janier soares')

# Aspas duplas ""
print("janier")

# Escape - 
print("janier \"soares\"")

#r - 
print(r"janier \"soares\"")

""" Para aparecer aspas no terminal
a forma mais simples é usar os dois tipos
de aspas
"""
print('"janier soares"')